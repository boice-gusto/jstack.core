        "## Domain rules — team metrics\n"
        "\n"
        "### Absolute rules\n"
        "1. Goodhart's Law governs every metric here: once a number becomes a target, people optimize the number, "
        "not the goal it was meant to represent. Name this explicitly whenever a metric is proposed as a target "
        "rather than a diagnostic signal.\n"
        "2. Velocity and story points measure **estimated effort**, not delivered value or productivity. They are "
        "team-relative and un-normalized by design — comparing velocity across teams, or using it to judge "
        "individual output, is a category error, not just a bad practice "
        "([Fowler: \"velocity is not a measure of productivity\"](https://www.artisanagility.com/blog/velocity-is-not-a-productivity-metric-and-never-was)).\n"
        "3. Report flow metrics with their real definitions, not colloquial synonyms: **cycle time** is time-in-"
        "process for one item; **throughput** is items completed per unit time; **WIP** is items currently in "
        "progress; **flow efficiency** is active time divided by total elapsed time.\n"
        "4. Apply **Little's Law** — WIP = throughput × cycle time — as a consistency check, not three independently "
        "estimated numbers. If reported WIP, throughput, and cycle time don't roughly satisfy the identity, one "
        "measurement is wrong or the system isn't in a steady state; say which is suspect.\n"
        "5. Report **percentiles (p50/p85 or p95), never a bare average**, for cycle time or any right-skewed "
        "duration metric. An average is dragged toward the fast bulk of the distribution and hides the long tail "
        "that actually generates complaints — the same failure mode as reporting mean latency instead of p95/p99.\n"
        "6. Never state a rate or percentage without its denominator visible in the same sentence. An unstated-"
        "denominator claim (\"80% of PRs reviewed within a day\") can be true and misleading simultaneously if the "
        "sample, window, or exclusions aren't named alongside it.\n"
        "7. Never compare individuals by these metrics. Team/flow-level only, and always paired with a quality "
        "signal (e.g. change-failure rate alongside throughput) so speed alone isn't read as the whole story.\n"
        "\n"
        "### Thresholds\n"
        "| Signal | Threshold | Why |\n"
        "|---|---|---|\n"
        "| Little's Law identity | WIP ≈ throughput × cycle time | If reported numbers don't roughly satisfy this, flag which measurement is likely wrong or the window isn't steady-state. |\n"
        "| Flow efficiency | typical unmanaged team: 15–40%; high-performing: 40–60% | Most elapsed time in an unmanaged flow is waiting (review queues, handoffs, approvals), not active work — 100% is neither realistic nor the goal ([Swarmia](https://www.swarmia.com/blog/flow-efficiency/)). |\n"
        "| Cycle-time reporting | report p50 **and** p85/p95 together, never a bare average | Duration distributions are right-skewed; the mean sits far from the typical case and hides the tail. |\n"
        "| Velocity comparison across teams | never valid (0 tolerance) | Story points aren't normalized across teams or estimators; a cross-team velocity comparison compares nothing meaningful. |\n"
        "| Denominator disclosure | 100% of published rate/percentage metrics state N and window in the same sentence/caption | Without it, the number can't be evaluated for whether it's meaningful or cherry-picked. |\n"
        "| WIP per person | practitioner guideline: 1-2 active items | Above this, context-switching cost and Little's Law both predict rising cycle time even with constant throughput. |\n"
        "\n"
        "### Named anti-patterns\n"
        "| Anti-pattern | Why wrong | What instead |\n"
        "|---|---|---|\n"
        "| Velocity as a productivity KPI | Goodhart's Law: teams inflate point estimates once velocity is tracked as a target | Track flow metrics (cycle time, throughput) instead; keep velocity internal to the originating team's own sprint planning |\n"
        "| Reporting average cycle time only | Right-skewed distributions make the mean dragged and unrepresentative — same shape problem as mean vs. p99 latency | Report percentiles (p50 + p85/p95) side by side |\n"
        "| Unstated-denominator rate (\"80% shipped on time\") | True and misleading simultaneously if N, window, or exclusions aren't stated | State N, window, and inclusion criteria in the same sentence |\n"
        "| Comparing individual engineers by ticket count/velocity | Goodhart at the person level, plus tickets/points vary wildly in size and aren't comparable across people | Report team/flow-level only; use qualitative review, not a ticket count, for individual signal |\n"
        "| Treating WIP, throughput, and cycle time as three independent facts | They're linked by Little's Law; reporting them without the identity misses an internal-consistency check and an obvious lever | Apply WIP = throughput × cycle time explicitly; recommend a WIP limit when cycle time is the actual complaint |\n"
        "\n"
        "### Worked example\n"
        "- **Weak:** \"Team velocity is up 20% this quarter, we're getting more productive.\"\n"
        "- **Sharp:** \"Story points completed per sprint rose ~20%, but average points-per-ticket also rose (5 "
        "points vs. 3 last quarter) — consistent with estimate inflation, a known Goodhart response once velocity "
        "started appearing in the quarterly review deck. The flow metrics tell a different story: median (p50) "
        "cycle time held flat at 3 days, but p85 cycle time rose from 6 to 11 days — a growing share of work is "
        "stuck in a long tail, mostly PRs waiting >48h for a second reviewer. Recommend dropping velocity from the "
        "quarterly deck and tracking p50/p85 cycle time plus WIP (currently ~2.4 items/engineer, above the 1-2 "
        "guideline) instead — capping WIP is the direct lever on the actual complaint (things take a long time to "
        "land), not a velocity target the numbers show is already being gamed.\"\n"
        "- The sharp version names the mechanism (estimate inflation under Goodhart's Law), the evidence (points-"
        "per-ticket drift, p50 vs. p85 divergence, WIP above guideline), and the fix (swap the tracked metric, cap "
        "WIP).\n"
        "\n"
        "### What this skill must not do\n"
        "- Not a performance-review or individual-ranking tool — team/flow-level only, ever.\n"
        "- Not invent org-specific velocity or story-point history — derive only from configured Jira/GitHub data, "
        "and label gaps rather than fill them.\n"
        "- Not a substitute for qualitative signal (interviews, retro themes) when the question is \"why,\" not "
        "just \"what changed.\"\n"
