        "| Stated- vs revealed-preference gap | trust revealed evidence when they conflict | Stated preference alone has been shown to substantially under-predict real behavior compared to behavioral methods. |\n"
        "| Verbatim quote per theme | ≥1 direct, attributed quote per major theme reported | A theme with no quote is a summarizer's paraphrase, not a finding. |\n"
